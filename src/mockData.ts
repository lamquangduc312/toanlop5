// ---------- Factory gọn để khai báo câu hỏi ----------
function bank(topicId: TopicId) {
  return {
    mc: (
      id: string,
      prompt: string,
      options: string[],
      answer: number,
      explanation: string,
      source: string,
      points?: number,
    ): MCQuestion => ({ id, topicId, type: 'mc', prompt, options, answer, explanation, source, points }),
    input: (
      id: string,
      prompt: string,
      answers: string | string[],
      explanation: string,
      source: string,
      unit?: string,
      points?: number,
    ): InputQuestion => ({
      id,
      topicId,
      type: 'input',
      prompt,
      answers: Array.isArray(answers) ? answers : [answers],
      explanation,
      source,
      unit,
      points,
    }),
  };
}

